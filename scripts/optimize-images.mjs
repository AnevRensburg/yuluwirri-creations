#!/usr/bin/env node
/**
 * Converts every original in images-src/ (jpg/png/webp) into AVIF + WebP at a few widths in
 * public/images, and writes the typed manifest <app-picture> reads. The image key is the file
 * name without its extension. Also builds the social preview (from the hero image) and favicons
 * (from `favicon.*`, else `logo.*`, else the hero image).
 *
 * Usage: node scripts/optimize-images.mjs <hero image key>
 */
import { mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'images-src');
const outDir = path.join(root, 'public/images');
const manifestFile = path.join(root, 'src/app/data/image-manifest.ts');
const heroKey = process.argv[2];

const WIDTHS = [480, 960, 1600];
const LOGO_WIDTHS = [160, 320];

const files = (await readdir(source)).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort();
const byKey = Object.fromEntries(files.map((f) => [f.replace(/\.[^.]+$/, ''), path.join(source, f)]));

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

const manifest = {};
for (const [key, input] of Object.entries(byKey)) {
  if (key === 'favicon') continue;
  const meta = await sharp(input).rotate().metadata();
  const targets = key === 'logo' ? LOGO_WIDTHS : WIDTHS;
  const orientedWidth = meta.orientation >= 5 ? meta.height : meta.width;
  const widths = [...new Set(targets.map((w) => Math.min(w, orientedWidth)))].sort((a, b) => a - b);
  let height = 0;
  for (const width of widths) {
    const img = sharp(input).rotate().resize({ width, withoutEnlargement: true });
    const out = path.join(outDir, `${key}-${width}`);
    const info = await img.clone().avif({ quality: 55, effort: 5 }).toFile(`${out}.avif`);
    await img.clone().webp({ quality: 78, effort: 5 }).toFile(`${out}.webp`);
    height = info.height;
  }
  manifest[key] = { width: widths.at(-1), height, widths };
  console.log(`${path.basename(input).padEnd(32)} -> ${key} [${widths.join(', ')}]`);
}

if (heroKey && byKey[heroKey]) {
  await sharp(byKey[heroKey])
    .rotate()
    .resize({ width: 1200, height: 630, fit: 'cover' })
    .jpeg({ quality: 80, mozjpeg: true })
    .toFile(path.join(outDir, 'og-image.jpg'));
}

const iconSource = byKey.favicon ?? byKey.logo ?? byKey[heroKey];
if (iconSource) {
  const square = (size) =>
    sharp(iconSource)
      .rotate()
      .resize({ width: size, height: size, fit: byKey.favicon || byKey.logo ? 'contain' : 'cover', background: '#ffffff' })
      .flatten({ background: '#ffffff' })
      .png({ compressionLevel: 9 });
  await square(48).toFile(path.join(root, 'public/favicon.png'));
  await square(180).toFile(path.join(root, 'public/apple-touch-icon.png'));
}

await mkdir(path.dirname(manifestFile), { recursive: true });
await writeFile(
  manifestFile,
  `// Generated by scripts/optimize-images.mjs. Do not edit by hand.\n\n` +
    `export interface ImageEntry {\n  readonly width: number;\n  readonly height: number;\n  readonly widths: readonly number[];\n}\n\n` +
    `export const IMAGE_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, ImageEntry>;\n\n` +
    `export type ImageKey = keyof typeof IMAGE_MANIFEST;\n`,
);
